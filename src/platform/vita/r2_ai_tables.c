float AI_fn_fClampDeltaTime(float fDeltaTime) {
    if (fDeltaTime < R2_AI_DT_MIN_CLAMP) return R2_AI_DT_MIN_CLAMP;
    if (fDeltaTime > R2_AI_DT_MAX_CLAMP) return R2_AI_DT_MAX_CLAMP;
    return fDeltaTime;
}
