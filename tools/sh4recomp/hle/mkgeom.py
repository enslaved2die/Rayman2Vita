#!/usr/bin/env python3
"""Generate hle/geomhooks.c: register-localised hooks of the TA vertex/triangle submit family (see hle/mkmath.py, same localiser, sq=True mode).
Differences to mathhooks.c: stores into the store-queue window 0xE0000000.. go straight into sh4_sq_buf (same bytes sh4_io_write would store), and `pref @Rn`
(sh4_pref) is a call out: registers are spilled, GEOM_PREF() runs the real flush (pref handler -> TA parse), registers are reloaded.
Check mode -DR2_CHK_GEOM: original and hook run from the same snapshot; ctx, 16 MiB RAM, the SQ buffer and the ordered list of pref flushes (address + SQ contents at that
moment) are compared; the original's flushes are then replayed into the real handler so the TA sees each flush exactly once.
usage: python3 hle/mkgeom.py [gen_fix|gen] ADDR [ADDR ...]   (writes hle/geomhooks.c)"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mkmath
from mkmath import localise, find_fn, Unsupported

HEAD = r'''/* GENERATED by hle/mkgeom.py - do not edit.  Register-localised hooks of the TA vertex / triangle submit routines.
 * Disable: -DR2_NO_GEOM_HOOKS (build), R2_NO_GEOM_HOOKS=1 (host env), empty file ux0:data/rayman2/NO_GEOM_HOOKS (Vita).
 * Verify: -DR2_CHK_GEOM (host; original + hook from the same snapshot, compares ctx, RAM, SQ buffer and every pref flush; summary at exit; R2_CHK_GEOM_EVERY=n samples). */
#include "hle.h"
#include "hle_priv.h"
#include "enter.h"
#include "runtime.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

extern uint8_t sh4_sq_buf[];
typedef hle_pref_fn geom_pref_fn;

/* store: RAM first (stack), then the store-queue window straight into the SQ buffer (what runtime.c sh4_io_write does for 4-byte stores), else the generic slow path */
static inline void STQ(uint32_t a, uint32_t v) {
    if (SH4_LIKELY(SH4_FASTQ(a))) memcpy(&sh4_ram[SH4_OFF(a)], &v, 4);
    else if (SH4_LIKELY((a & 0xFC000000u) == 0xE0000000u)) memcpy(sh4_sq_buf + (a & 0x3F), &v, 4);
    else sh4_io_write(a, 4, v);
}
#define GEOM_PREF(c, a) sh4_pref((c), (a))

'''

CHK = r'''
#ifdef R2_CHK_GEOM
#include <time.h>
static uint8_t chk_snap[SH4_RAM_SIZE], chk_res[SH4_RAM_SIZE];
typedef struct { uint32_t addr; uint8_t sq[64]; } PrefRec;
#define MAXREC 4096
static PrefRec rec_a[MAXREC], rec_b[MAXREC]; static int nrec_a, nrec_b; static PrefRec *rec_cur; static int *nrec_cur;
static struct { unsigned long calls, bad_ctx, bad_ram, bad_sq, bad_pref, prefs; double t_orig, t_fast; } chk_st[%(n)d];
static const char *chk_names[%(n)d] = { %(names)s };
static const uint32_t chk_addrs[%(n)d] = { %(addrs)s };
static unsigned long chk_every, chk_seq;
static double now_s(void) { struct timespec ts; clock_gettime(CLOCK_MONOTONIC, &ts); return ts.tv_sec + ts.tv_nsec * 1e-9; }
static void chk_report(void) {
    for (int i = 0; i < %(n)d; i++) if (chk_st[i].calls)
        fprintf(stderr, "[chk-geom] %%s: %%lu calls checked (%%lu pref flushes), mismatches: ctx %%lu RAM %%lu SQ-buffer %%lu pref %%lu | host time orig %%.3f ms hook %%.3f ms (%%.2fx; host, not Vita)\n", chk_names[i], chk_st[i].calls,
                chk_st[i].prefs, chk_st[i].bad_ctx, chk_st[i].bad_ram, chk_st[i].bad_sq, chk_st[i].bad_pref, chk_st[i].t_orig * 1e3, chk_st[i].t_fast * 1e3, chk_st[i].t_fast > 0 ? chk_st[i].t_orig / chk_st[i].t_fast : 0.0);
}
static void rec_pref(SH4Ctx *c, uint32_t a) { (void)c; if (*nrec_cur < MAXREC) { rec_cur[*nrec_cur].addr = a; memcpy(rec_cur[*nrec_cur].sq, sh4_sq_buf, 64); } (*nrec_cur)++; }
static void chk_run(SH4Ctx *c, int idx, void (*fast)(SH4Ctx *)) {
    static int init; if (!init) { init = 1; const char *e = getenv("R2_CHK_GEOM_EVERY"); chk_every = e ? strtoul(e, 0, 10) : 1; if (!chk_every) chk_every = 1; atexit(chk_report); }
    if (chk_seq++ %% chk_every) { fast(c); return; }
    geom_pref_fn real = hle_get_pref_handler();
    uint8_t sq0[72], sq_o[72];
    memcpy(chk_snap, sh4_ram, SH4_RAM_SIZE); memcpy(sq0, sh4_sq_buf, 72);
    SH4Ctx c0 = *c, c2 = *c;
    hle_set_pref_handler(rec_pref);
    rec_cur = rec_a; nrec_cur = &nrec_a; nrec_a = 0;
    double t0 = now_s(); hle_orig(&c2, chk_addrs[idx]); double t1 = now_s();
    memcpy(chk_res, sh4_ram, SH4_RAM_SIZE); memcpy(sq_o, sh4_sq_buf, 72);
    memcpy(sh4_ram, chk_snap, SH4_RAM_SIZE); memcpy(sh4_sq_buf, sq0, 72);
    rec_cur = rec_b; nrec_cur = &nrec_b; nrec_b = 0;
    double t2 = now_s(); fast(c); double t3 = now_s();
    hle_set_pref_handler(real);
    chk_st[idx].calls++; chk_st[idx].t_orig += t1 - t0; chk_st[idx].t_fast += t3 - t2; chk_st[idx].prefs += (unsigned long)nrec_a;
    if (memcmp(c, &c2, sizeof c2)) {
        chk_st[idx].bad_ctx++;
        if (chk_st[idx].bad_ctx <= 8) {
            fprintf(stderr, "[chk-geom] %%s CTX MISMATCH (call %%lu):", chk_names[idx], chk_st[idx].calls);
            for (int i = 0; i < 16; i++) if (c->r[i] != c2.r[i]) fprintf(stderr, " r%%d hook=%%08x orig=%%08x (in %%08x)", i, c->r[i], c2.r[i], c0.r[i]);
            for (int i = 0; i < 16; i++) if (c->fr[i] != c2.fr[i]) fprintf(stderr, " fr%%d hook=%%08x orig=%%08x", i, c->fr[i], c2.fr[i]);
            for (int i = 0; i < 16; i++) if (c->xf[i] != c2.xf[i]) fprintf(stderr, " xf%%d", i);
            if (c->t != c2.t) fprintf(stderr, " t hook=%%u orig=%%u", c->t, c2.t);
            if (c->pr != c2.pr) fprintf(stderr, " pr hook=%%08x orig=%%08x", c->pr, c2.pr);
            if (c->fpul != c2.fpul) fprintf(stderr, " fpul");
            if (c->fpscr != c2.fpscr) fprintf(stderr, " fpscr");
            fprintf(stderr, "\n");
        }
    }
    if (memcmp(chk_res, sh4_ram, SH4_RAM_SIZE)) {
        chk_st[idx].bad_ram++;
        if (chk_st[idx].bad_ram <= 8) {
            unsigned shown = 0; fprintf(stderr, "[chk-geom] %%s RAM MISMATCH (call %%lu):", chk_names[idx], chk_st[idx].calls);
            for (uint32_t k = 0; k < SH4_RAM_SIZE && shown < 12; k++) if (chk_res[k] != sh4_ram[k]) { fprintf(stderr, " %%06x(orig %%02x hook %%02x)", k, chk_res[k], sh4_ram[k]); shown++; }
            fprintf(stderr, "\n");
        }
    }
    if (memcmp(sq_o, sh4_sq_buf, 72)) { chk_st[idx].bad_sq++; if (chk_st[idx].bad_sq <= 8) fprintf(stderr, "[chk-geom] %%s SQ BUFFER MISMATCH (call %%lu)\n", chk_names[idx], chk_st[idx].calls); }
    int bad = nrec_a != nrec_b || nrec_a > MAXREC;
    for (int i = 0; !bad && i < nrec_a; i++) if (rec_a[i].addr != rec_b[i].addr || memcmp(rec_a[i].sq, rec_b[i].sq, 64)) bad = 1;
    if (bad) { chk_st[idx].bad_pref++; if (chk_st[idx].bad_pref <= 8) fprintf(stderr, "[chk-geom] %%s PREF FLUSH MISMATCH (call %%lu): orig %%d flushes, hook %%d\n", chk_names[idx], chk_st[idx].calls, nrec_a, nrec_b); }
    /* continue on the original's result; replay its flushes into the real handler (TA sees each exactly once) */
    memcpy(sh4_ram, chk_res, SH4_RAM_SIZE); *c = c2;
    for (int i = 0; i < nrec_a && i < MAXREC; i++) { memcpy(sh4_sq_buf, rec_a[i].sq, 64); if (real) real(c, rec_a[i].addr); }
    memcpy(sh4_sq_buf, sq_o, 72);
}
#endif
'''


def main():
    gen = "gen_fix"
    a_ = sys.argv[1:]
    if a_ and a_[0] in ("gen", "gen_fix"):
        gen = a_.pop(0)
    mkmath.gen = gen
    addrs = a_ or ["8c0352d6"]
    fns = []
    for a in addrs:
        a = a.lower().replace("0x", "")
        try:
            decl, code = localise(a, find_fn(a), sq=True)
        except Unsupported as e:
            sys.stderr.write("skipped f_%s: unsupported construct %s\n" % (a, e)); continue
        fns.append((a, decl, code))
    o = [HEAD]
    for a, decl, code in fns:
        o.append("static void h_geom_%s(SH4Ctx *c) {\n"
                 "    if (c->fpscr & (SH4_FPSCR_SZ | SH4_FPSCR_PR)) { hle_orig(c, 0x%s); return; }      /* guest runs this with SZ = PR = 0; anything else takes the original body */\n"
                 "    HLE_ENTER(0x%s);\n%s%s}\n\n" % (a, a.upper(), a.upper(), decl, code))
    n = len(fns)
    o.append(CHK % dict(n=n, names=", ".join('"f_%s"' % a for a, _, _ in fns), addrs=", ".join("0x%sU" % a.upper() for a, _, _ in fns)))
    o.append("#ifdef R2_CHK_GEOM\n")
    for i, (a, _, _) in enumerate(fns):
        o.append("static void chk_%s(SH4Ctx *c) { chk_run(c, %d, h_geom_%s); }\n" % (a, i, a))
    o.append("#endif\n\nvoid hle_geomhooks_init(void) {\n#ifndef R2_NO_GEOM_HOOKS\n    if (getenv(\"R2_NO_GEOM_HOOKS\")) return;\n")
    for a, _, _ in fns:
        o.append("#ifdef R2_CHK_GEOM\n    hle_hook(0x%s, chk_%s);\n#else\n    hle_hook(0x%s, h_geom_%s);\n#endif\n" % (a.upper(), a, a.upper(), a))
    o.append("#endif\n}\n")
    open(os.path.join(mkmath.root, "hle", "geomhooks.c"), "w").write("".join(o))
    sys.stderr.write("generated hle/geomhooks.c: %s\n" % ", ".join("f_" + a for a, _, _ in fns))


main()
