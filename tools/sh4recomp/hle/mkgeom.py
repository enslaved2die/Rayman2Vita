#!/usr/bin/env python3
"""Generate hle/geomhooks.c: register-localised native hooks of the Kamui / GLI triangle + vertex submit family.

Same mechanical transcription as hle/mkmath.py (it imports its localiser: guest registers in C locals, calls out spill/reload through sh4_call), plus:
  * every guest store goes through STQ(): a 4-byte store into the store-queue window 0xE0000000..0xE3FFFFFF is written straight into sh4_sq_buf (byte-identical to what
    runtime.c sh4_io_write does for that window, minus the out-of-line call and the dispatch), anything else takes the normal ST32 path;
  * sh4_pref(c, addr) stays a call (SQ -> TA flush semantic untouched).  The locals are NOT spilled around it: the pref handler (boot.c sq_flush_default -> TA sink)
    neither reads nor writes the guest registers;
  * fp_cmp is inlined (PR = 0).
Verification (host): build with -DR2_CHK_GEOM; every sampled top-level call runs the original body and the hook from the same snapshot (16 MiB RAM, ctx, SQ buffer) and
compares ctx + RAM + SQ buffer + the ordered list of pref flushes (address and the 64 SQ bytes at flush time).  The original's flushes are then replayed into the real TA
handler, so the TA sees exactly what the unhooked game sends.  R2_CHK_GEOM_EVERY=n samples every n-th top-level call.
Disable: -DR2_NO_GEOM_HOOKS at build time, env R2_NO_GEOM_HOOKS=1 (host) / empty file ux0:data/rayman2/NO_GEOM_HOOKS (Vita; boot.c).

usage: python3 hle/mkgeom.py [gen_fix|gen] ADDR [ADDR ...]   (writes hle/geomhooks.c)"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mkmath
from mkmath import localise, find_fn, Unsupported

HEAD = r'''/* GENERATED by hle/mkgeom.py - do not edit.  Register-localised native hooks of the Kamui / GLI vertex + triangle submit family (see the generator's header comment).
 * Disable: -DR2_NO_GEOM_HOOKS (build), R2_NO_GEOM_HOOKS=1 (host env), empty file ux0:data/rayman2/NO_GEOM_HOOKS (Vita).  Verify: -DR2_CHK_GEOM (host), R2_CHK_GEOM_EVERY=n. */
#include "hle.h"
#include "hle_priv.h"
#include "enter.h"
#include "runtime.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

extern uint8_t sh4_sq_buf[];

/* same expressions as runtime.h fp_arith / fp_fmac (PR = 0 path) on fr bit patterns */
static inline uint32_t L_arith(SH4Ctx *c, int op, uint32_t xa, uint32_t xb) {
    float a = fin(c, xa), b = fin(c, xb), r;
    switch (op) { case 0: r = a + b; break; case 1: r = a - b; break; case 2: r = a * b; break; default: r = a / b; }
    return nanfix(fout(c, r), xa, xb);
}
#ifdef SH4_FASTFP
static inline uint32_t L_fmac(SH4Ctx *c, uint32_t f0, uint32_t m, uint32_t n) { return fout(c, fin(c, f0) * fin(c, m) + fin(c, n)); }
#else
static inline uint32_t L_fmac(SH4Ctx *c, uint32_t f0, uint32_t m, uint32_t n) { return fout(c, fmaf(fin(c, f0), fin(c, m), fin(c, n))); }
#endif

/* host diagnostic -DR2_GEOM_STATS: per hook, entries and fallbacks to the original body (by FPSCR.SZ / FPSCR.PR), printed at exit */
#ifdef R2_GEOM_STATS
static struct { unsigned long n, fb_sz, fb_pr; } geom_st[%(n)d];
static const char *geom_nm[%(n)d] = { %(names)s };
static void geom_stat_report(void) { for (int i = 0; i < %(n)d; i++) fprintf(stderr, "[geom-stats] %%s: %%lu entries, fallbacks to original: SZ=1 %%lu, PR=1 %%lu\n", geom_nm[i], geom_st[i].n, geom_st[i].fb_sz, geom_st[i].fb_pr); }
static void GEOM_STAT_ENTER(int i, SH4Ctx *c) { static int init; if (!init) { init = 1; atexit(geom_stat_report); } geom_st[i].n++; if (c->fpscr & SH4_FPSCR_SZ) geom_st[i].fb_sz++; else if (c->fpscr & SH4_FPSCR_PR) geom_st[i].fb_pr++; }
#else
#define GEOM_STAT_ENTER(i, c) ((void)0)
#endif

/* 32-bit guest store: SQ window straight into the SQ buffer (== runtime.c sh4_io_write for 0xE0..), everything else as ST32 */
static inline void STQ(uint32_t a, uint32_t v) {
    if (SH4_LIKELY((a & 0xFC000000u) == 0xE0000000u)) *(uint32_t *)(void *)(sh4_sq_buf + (a & 0x3F)) = v;
    else ST32(a, v);
}

'''

CHK = r'''
#ifdef R2_CHK_GEOM
#include <time.h>
#define CHK_PG 4096u
#define CHK_NPG (SH4_RAM_SIZE / CHK_PG)
#define CHK_MAXPREF 16384
typedef struct { uint32_t addr; uint8_t sq[64]; } ChkPref;
static uint8_t chk_snap[SH4_RAM_SIZE], chk_res[SH4_RAM_SIZE];
static uint8_t chk_dirty[CHK_NPG];
static ChkPref chk_logA[CHK_MAXPREF], chk_logB[CHK_MAXPREF];
static unsigned chk_nA, chk_nB, chk_over;
static struct { unsigned long calls, nested, bad_ctx, bad_ram, bad_sq, bad_pref; double t_orig, t_fast; } chk_st[%(n)d];
static const char *chk_names[%(n)d] = { %(names)s };
static const uint32_t chk_addrs[%(n)d] = { %(addrs)s };
static unsigned long chk_every, chk_seq;
static int chk_mode;                 /* 0 = top level, 1 = running the original (nested hooked calls take their original too), 2 = running the hooks */
static unsigned long chk_pref_total;
static hle_pref_fn chk_real_pref;
static double now_s(void) { struct timespec ts; clock_gettime(CLOCK_MONOTONIC, &ts); return ts.tv_sec + ts.tv_nsec * 1e-9; }
static void chk_report(void) {
    unsigned long tot_bad = 0, tot = 0;
    for (int i = 0; i < %(n)d; i++) {
        tot += chk_st[i].calls; tot_bad += chk_st[i].bad_ctx + chk_st[i].bad_ram + chk_st[i].bad_sq + chk_st[i].bad_pref;
        if (chk_st[i].calls)
            fprintf(stderr, "[chk-geom] %%s: %%lu top-level calls checked (%%lu nested hook calls inside them), mismatches ctx %%lu RAM %%lu SQ %%lu pref-log %%lu | host time orig %%.3f ms hook %%.3f ms (%%.2fx; -O1 host, not Vita)\n",
                    chk_names[i], chk_st[i].calls, chk_st[i].nested, chk_st[i].bad_ctx, chk_st[i].bad_ram, chk_st[i].bad_sq, chk_st[i].bad_pref, chk_st[i].t_orig * 1e3, chk_st[i].t_fast * 1e3,
                    chk_st[i].t_fast > 0 ? chk_st[i].t_orig / chk_st[i].t_fast : 0.0);
    }
    fprintf(stderr, "[chk-geom] TOTAL %%lu calls checked, %%lu mismatches, %%lu pref flushes compared, %%u calls skipped (pref log overflow)\n", tot, tot_bad, chk_pref_total, chk_over);
}
static void chk_cap_pref(SH4Ctx *c, uint32_t addr) {
    (void)c;
    ChkPref *l = chk_mode == 1 ? chk_logA : chk_logB; unsigned *n = chk_mode == 1 ? &chk_nA : &chk_nB;
    if (*n < CHK_MAXPREF) { l[*n].addr = addr; memcpy(l[*n].sq, sh4_sq_buf, 64); }
    (*n)++;
}
static void chk_run(SH4Ctx *c, int idx, void (*fast)(SH4Ctx *)) {
    if (chk_mode == 1) { hle_orig(c, chk_addrs[idx]); return; }
    if (chk_mode == 2) { chk_st[idx].nested++; fast(c); return; }
    static int init; if (!init) { init = 1; const char *e = getenv("R2_CHK_GEOM_EVERY"); chk_every = e ? strtoul(e, 0, 10) : 1; if (!chk_every) chk_every = 1; atexit(chk_report); }
    if (chk_seq++ %% chk_every) { fast(c); return; }
    chk_real_pref = hle_get_pref_handler();
    memcpy(chk_snap, sh4_ram, SH4_RAM_SIZE);
    uint8_t sq0[72]; memcpy(sq0, sh4_sq_buf, 72);
    SH4Ctx c0 = *c, c2 = *c;
    /* 1. original, pref flushes captured (not forwarded) */
    chk_nA = chk_nB = 0; chk_mode = 1; hle_set_pref_handler(chk_cap_pref);
    double t0 = now_s(); hle_orig(&c2, chk_addrs[idx]); double t1 = now_s();
    chk_mode = 0;
    uint8_t sqA[72]; memcpy(sqA, sh4_sq_buf, 72);
    /* pages the original changed: keep their result, restore the snapshot */
    for (unsigned p = 0; p < CHK_NPG; p++) {
        chk_dirty[p] = memcmp(chk_snap + p * CHK_PG, sh4_ram + p * CHK_PG, CHK_PG) != 0;
        if (chk_dirty[p]) { memcpy(chk_res + p * CHK_PG, sh4_ram + p * CHK_PG, CHK_PG); memcpy(sh4_ram + p * CHK_PG, chk_snap + p * CHK_PG, CHK_PG); }
    }
    memcpy(sh4_sq_buf, sq0, 72);
    /* 2. the hook from the same state */
    chk_mode = 2;
    double t2 = now_s(); fast(c); double t3 = now_s();
    chk_mode = 0; hle_set_pref_handler(chk_real_pref);
    chk_st[idx].calls++; chk_st[idx].t_orig += t1 - t0; chk_st[idx].t_fast += t3 - t2;
    if (chk_nA > CHK_MAXPREF || chk_nB > CHK_MAXPREF) { chk_over++; chk_st[idx].calls--; }
    else {
        if (memcmp(c, &c2, sizeof c2)) {
            chk_st[idx].bad_ctx++;
            if (chk_st[idx].bad_ctx <= 8) {
                fprintf(stderr, "[chk-geom] %%s CTX MISMATCH (call %%lu):", chk_names[idx], chk_st[idx].calls);
                for (int i = 0; i < 16; i++) if (c->r[i] != c2.r[i]) fprintf(stderr, " r%%d hook=%%08x orig=%%08x (in %%08x)", i, c->r[i], c2.r[i], c0.r[i]);
                for (int i = 0; i < 16; i++) if (c->fr[i] != c2.fr[i]) fprintf(stderr, " fr%%d hook=%%08x orig=%%08x (in %%08x)", i, c->fr[i], c2.fr[i], c0.fr[i]);
                for (int i = 0; i < 16; i++) if (c->xf[i] != c2.xf[i]) fprintf(stderr, " xf%%d", i);
                if (c->t != c2.t) fprintf(stderr, " t hook=%%u orig=%%u", c->t, c2.t);
                if (c->pr != c2.pr) fprintf(stderr, " pr hook=%%08x orig=%%08x", c->pr, c2.pr);
                if (c->fpul != c2.fpul) fprintf(stderr, " fpul hook=%%08x orig=%%08x", c->fpul, c2.fpul);
                if (c->fpscr != c2.fpscr) fprintf(stderr, " fpscr hook=%%08x orig=%%08x", c->fpscr, c2.fpscr);
                fprintf(stderr, " [other fields differ: %%d]\n", memcmp(c->rb, c2.rb, sizeof c2.rb) != 0 || c->gbr != c2.gbr || c->macl != c2.macl || c->mach != c2.mach);
            }
        }
        int ram_bad = 0;
        for (unsigned p = 0; p < CHK_NPG && !ram_bad; p++) {
            const uint8_t *want = chk_dirty[p] ? chk_res + p * CHK_PG : chk_snap + p * CHK_PG;
            if (memcmp(sh4_ram + p * CHK_PG, want, CHK_PG)) {
                ram_bad = 1; chk_st[idx].bad_ram++;
                if (chk_st[idx].bad_ram <= 8) {
                    unsigned shown = 0; fprintf(stderr, "[chk-geom] %%s RAM MISMATCH (call %%lu) sp=%%08x:", chk_names[idx], chk_st[idx].calls, c0.r[15]);
                    for (uint32_t k = 0; k < CHK_PG && shown < 12; k++) if (sh4_ram[p * CHK_PG + k] != want[k]) { fprintf(stderr, " %%06x(orig %%02x hook %%02x)", p * CHK_PG + k, want[k], sh4_ram[p * CHK_PG + k]); shown++; }
                    fprintf(stderr, "\n");
                }
            }
        }
        if (memcmp(sqA, sh4_sq_buf, 72)) { chk_st[idx].bad_sq++; if (chk_st[idx].bad_sq <= 8) fprintf(stderr, "[chk-geom] %%s SQ BUFFER MISMATCH (call %%lu)\n", chk_names[idx], chk_st[idx].calls); }
        int pb = chk_nA != chk_nB;
        for (unsigned i = 0; !pb && i < chk_nA; i++) pb = chk_logA[i].addr != chk_logB[i].addr || memcmp(chk_logA[i].sq, chk_logB[i].sq, 64);
        chk_pref_total += chk_nA;
        if (pb) { chk_st[idx].bad_pref++; if (chk_st[idx].bad_pref <= 8) fprintf(stderr, "[chk-geom] %%s PREF LOG MISMATCH (call %%lu): orig %%u flushes, hook %%u\n", chk_names[idx], chk_st[idx].calls, chk_nA, chk_nB); }
    }
    /* 3. continue on the original's result: dirty pages <- original, SQ buffer + TA flushes replayed from the original's log */
    for (unsigned p = 0; p < CHK_NPG; p++) if (chk_dirty[p]) memcpy(sh4_ram + p * CHK_PG, chk_res + p * CHK_PG, CHK_PG); else if (memcmp(sh4_ram + p * CHK_PG, chk_snap + p * CHK_PG, CHK_PG)) memcpy(sh4_ram + p * CHK_PG, chk_snap + p * CHK_PG, CHK_PG);
    *c = c2;
    for (unsigned i = 0; i < chk_nA && i < CHK_MAXPREF; i++) { memcpy(sh4_sq_buf, chk_logA[i].sq, 64); if (chk_real_pref) chk_real_pref(c, chk_logA[i].addr); }
    memcpy(sh4_sq_buf, sqA, 72);
}
#endif
'''


def main():
    args_ = sys.argv[1:]
    if args_ and args_[0] in ("gen", "gen_fix"):
        mkmath.gen = args_.pop(0)
    addrs = [a.lower().replace("0x", "") for a in args_]
    fns, skipped = [], []
    for a in addrs:
        body = find_fn(a)
        try:
            decl, code = localise(a, body, sq=True)
        except Unsupported as e:
            skipped.append((a, str(e)))
            continue
        fns.append((a, decl, code))
    for a, why in skipped:
        sys.stderr.write("skipped f_%s: unsupported construct %s\n" % (a, why))
    o = [HEAD % dict(n=len(fns), names=", ".join('"f_%s"' % a for a, _, _ in fns))]
    for a, decl, code in fns:
        o.append("static void h_geom_%s(SH4Ctx *c) {\n"
                 "    GEOM_STAT_ENTER(%d, c);\n"
                 "    if (c->fpscr & (SH4_FPSCR_SZ | SH4_FPSCR_PR)) { hle_orig(c, 0x%s); return; }      /* the guest only runs this with SZ = PR = 0; anything else takes the original body */\n"
                 "    HLE_ENTER(0x%s);\n%s%s}\n\n" % (a, [x[0] for x in fns].index(a), a.upper(), a.upper(), decl, code))
    n = len(fns)
    o.append(CHK % dict(n=n, names=", ".join('"f_%s"' % a for a, _, _ in fns), addrs=", ".join("0x%sU" % a.upper() for a, _, _ in fns)))
    o.append("#ifdef R2_CHK_GEOM\n")
    for i, (a, _, _) in enumerate(fns):
        o.append("static void chk_%s(SH4Ctx *c) { chk_run(c, %d, h_geom_%s); }\n" % (a, i, a))
    o.append("#endif\n\nvoid hle_geomhooks_init(void) {\n#ifndef R2_NO_GEOM_HOOKS\n    if (getenv(\"R2_NO_GEOM_HOOKS\")) return;\n")
    for a, _, _ in fns:
        o.append("#ifdef R2_CHK_GEOM\n    hle_hook(0x%s, chk_%s);\n#else\n    hle_hook(0x%s, h_geom_%s);\n#endif\n" % (a.upper(), a, a.upper(), a))
    o.append("#endif\n}\n")
    open(os.path.join(mkmath.root, "hle", "geomhooks.c"), "w").write("".join(o))
    sys.stderr.write("generated hle/geomhooks.c: %s\n" % ", ".join("f_" + a for a, _, _ in fns))


if __name__ == "__main__":
    main()
